create or replace function public.portal_create_order(
  p_client_request_id uuid,
  p_portal_reference text,
  p_organization text,
  p_location_license text,
  p_location_name text,
  p_submitted_by uuid,
  p_submitted_by_email text,
  p_submitted_by_role text,
  p_state text,
  p_owner_approval_required boolean,
  p_approval_threshold_cents integer,
  p_order_value_cents integer,
  p_contains_preorder boolean,
  p_release_hold boolean,
  p_delivery_window text,
  p_receiving_contact text,
  p_receiving_instructions text,
  p_lines jsonb,
  p_metadata jsonb default '{}'::jsonb
)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  created_order_id uuid;
  existing_order public.portal_order%rowtype;
  computed_order_value_cents bigint;
  request_fingerprint text;
begin
  if jsonb_typeof(p_lines) <> 'array' or jsonb_array_length(p_lines) < 1 or jsonb_array_length(p_lines) > 250 then
    raise exception 'An order must contain between one and 250 lines';
  end if;

  select coalesce(sum((line.value ->> 'lineTotalCents')::bigint), 0)
  into computed_order_value_cents
  from jsonb_array_elements(p_lines) as line(value);

  if computed_order_value_cents <> p_order_value_cents then
    raise exception 'The order value does not match its verified lines';
  end if;
  if exists (
    select 1
    from jsonb_array_elements(p_lines) as line(value)
    where (line.value ->> 'lineTotalCents')::bigint
      <> (line.value ->> 'quantity')::bigint * (line.value ->> 'unitPriceCents')::bigint
  ) then
    raise exception 'An order line total is invalid';
  end if;

  request_fingerprint := md5(jsonb_build_object(
    'portalReference', trim(p_portal_reference),
    'organization', p_organization,
    'locationLicense', p_location_license,
    'submittedBy', p_submitted_by,
    'submittedByRole', p_submitted_by_role,
    'state', p_state,
    'orderValueCents', p_order_value_cents,
    'deliveryWindow', p_delivery_window,
    'receivingContact', p_receiving_contact,
    'receivingInstructions', p_receiving_instructions,
    'lines', p_lines
  )::text);

  insert into public.portal_order (
    client_request_id, portal_reference, organization, location_license,
    location_name, submitted_by, submitted_by_email, submitted_by_role,
    state, owner_approval_required, approval_threshold_cents,
    order_value_cents, contains_preorder, release_hold, delivery_window,
    receiving_contact, receiving_instructions, metadata
  ) values (
    p_client_request_id, trim(p_portal_reference), p_organization,
    p_location_license, p_location_name, p_submitted_by,
    nullif(trim(coalesce(p_submitted_by_email, '')), ''), p_submitted_by_role,
    p_state, p_owner_approval_required, p_approval_threshold_cents,
    p_order_value_cents, p_contains_preorder, p_release_hold,
    nullif(trim(coalesce(p_delivery_window, '')), ''),
    nullif(trim(coalesce(p_receiving_contact, '')), ''),
    nullif(trim(coalesce(p_receiving_instructions, '')), ''),
    coalesce(p_metadata, '{}'::jsonb) || jsonb_build_object('_requestFingerprint', request_fingerprint)
  )
  on conflict (client_request_id) do nothing
  returning id into created_order_id;

  if created_order_id is null then
    select * into existing_order
    from public.portal_order
    where client_request_id = p_client_request_id;
    if existing_order.metadata ->> '_requestFingerprint' is distinct from request_fingerprint then
      raise exception 'The idempotency identifier belongs to a different verified order';
    end if;
    return jsonb_build_object(
      'id', existing_order.id,
      'created', false,
      'workflowState', existing_order.workflow_state,
      'orderNumber', existing_order.order_number,
      'portalReference', existing_order.portal_reference,
      'state', existing_order.state
    );
  end if;

  insert into public.portal_order_line (
    order_id, line_number, product_id, product_name, sku, compliance_tag,
    quantity, unit, unit_price_cents, line_total_cents, order_mode, release_state
  )
  select
    created_order_id,
    line.ordinality::integer,
    trim(line.value ->> 'productId'),
    trim(line.value ->> 'product'),
    nullif(trim(coalesce(line.value ->> 'sku', '')), ''),
    nullif(trim(coalesce(line.value ->> 'tag', '')), ''),
    (line.value ->> 'quantity')::integer,
    coalesce(nullif(trim(line.value ->> 'unit'), ''), 'each'),
    (line.value ->> 'unitPriceCents')::integer,
    (line.value ->> 'lineTotalCents')::integer,
    coalesce(nullif(trim(line.value ->> 'orderMode'), ''), 'standard'),
    coalesce(nullif(trim(line.value ->> 'releaseState'), ''), 'released')
  from jsonb_array_elements(p_lines) with ordinality as line(value, ordinality);

  insert into public.portal_order_event (
    order_id, source, from_state, to_state, actor_id, actor_email, note, metadata
  ) values (
    created_order_id, 'portal-intake', null, p_state, p_submitted_by,
    nullif(trim(coalesce(p_submitted_by_email, '')), ''),
    'Order verified and submitted to the portal intake.',
    jsonb_build_object('clientRequestId', p_client_request_id)
  );

  return jsonb_build_object(
    'id', created_order_id,
    'created', true,
    'workflowState', 'pending',
    'orderNumber', null,
    'portalReference', trim(p_portal_reference),
    'state', p_state
  );
end;
$$;

create or replace function public.portal_mark_order_workflow(
  p_order_id uuid,
  p_workflow_state text,
  p_order_number text default null,
  p_monday_item_id text default null,
  p_monday_board_id text default null,
  p_error text default null,
  p_metadata jsonb default '{}'::jsonb
)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  changed public.portal_order%rowtype;
begin
  if p_workflow_state not in ('pending', 'accepted', 'needs_reconciliation', 'rejected') then
    raise exception 'Unsupported workflow state';
  end if;

  update public.portal_order
  set workflow_state = p_workflow_state,
      order_number = case when p_workflow_state = 'accepted' then nullif(trim(coalesce(p_order_number, '')), '') else order_number end,
      monday_item_id = coalesce(nullif(trim(coalesce(p_monday_item_id, '')), ''), monday_item_id),
      monday_board_id = coalesce(nullif(trim(coalesce(p_monday_board_id, '')), ''), monday_board_id),
      workflow_error = nullif(trim(coalesce(p_error, '')), ''),
      accepted_at = case when p_workflow_state = 'accepted' then coalesce(accepted_at, now()) else accepted_at end,
      metadata = metadata || coalesce(p_metadata, '{}'::jsonb),
      updated_at = now()
  where id = p_order_id
  returning * into changed;

  if not found then raise exception 'Portal order not found'; end if;

  if p_workflow_state = 'accepted' then
    insert into public.portal_order_event (
      order_id, source, from_state, to_state, raw_status, note, metadata
    ) values (
      changed.id, 'system', changed.state, changed.state, 'workflow_accepted',
      'Monday accepted the portal order intake.', coalesce(p_metadata, '{}'::jsonb)
    );
  end if;

  return jsonb_build_object(
    'id', changed.id,
    'workflowState', changed.workflow_state,
    'orderNumber', changed.order_number,
    'mondayItemId', changed.monday_item_id,
    'state', changed.state
  );
end;
$$;

create or replace function public.portal_apply_order_transition(
  p_order_id uuid,
  p_expected_state text,
  p_target_state text,
  p_actor_id uuid,
  p_actor_email text,
  p_source text,
  p_note text default null,
  p_raw_status text default null,
  p_metadata jsonb default '{}'::jsonb,
  p_release_hold boolean default null,
  p_enqueue_monday boolean default true
)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  current_order public.portal_order%rowtype;
  created_event_id uuid;
begin
  select * into current_order
  from public.portal_order
  where id = p_order_id
  for update;

  if not found then raise exception 'Portal order not found'; end if;
  if current_order.state <> p_expected_state then raise exception 'Order state changed; refresh before trying again'; end if;
  if p_source not in ('store-owner', 'store-user', 'internal', 'monday', 'system') then raise exception 'Unsupported order event source'; end if;

  update public.portal_order
  set state = p_target_state,
      release_hold = coalesce(p_release_hold, release_hold),
      updated_at = now()
  where id = p_order_id;

  insert into public.portal_order_event (
    order_id, source, from_state, to_state, actor_id, actor_email,
    raw_status, note, metadata
  ) values (
    p_order_id, p_source, p_expected_state, p_target_state, p_actor_id,
    nullif(trim(coalesce(p_actor_email, '')), ''),
    nullif(trim(coalesce(p_raw_status, '')), ''),
    nullif(trim(coalesce(p_note, '')), ''),
    coalesce(p_metadata, '{}'::jsonb)
  ) returning id into created_event_id;

  if p_enqueue_monday then
    insert into public.portal_order_sync_outbox (order_id, event_id)
    values (p_order_id, created_event_id)
    on conflict (event_id, target) do nothing;
  end if;

  return jsonb_build_object(
    'orderId', p_order_id,
    'eventId', created_event_id,
    'fromState', p_expected_state,
    'toState', p_target_state,
    'releaseHold', coalesce(p_release_hold, current_order.release_hold),
    'syncQueued', p_enqueue_monday
  );
end;
$$;


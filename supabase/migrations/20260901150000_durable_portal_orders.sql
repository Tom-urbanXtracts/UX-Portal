-- Durable portal orders. Monday remains the work-management destination, but
-- the portal owns the customer-facing order record and event history so an
-- accepted order survives refreshes and cannot be changed only in a browser.

create table if not exists public.portal_order (
  id uuid primary key default gen_random_uuid(),
  client_request_id uuid not null unique,
  portal_reference text not null unique,
  order_number text,
  monday_item_id text,
  monday_board_id text,
  organization text not null,
  location_license text not null references public.portal_store(license_number),
  location_name text not null,
  submitted_by uuid references auth.users(id) on delete set null,
  submitted_by_email text,
  submitted_by_role text not null check (submitted_by_role in ('owner', 'buyer', 'internal')),
  state text not null check (state in (
    'awaiting_owner_approval', 'ordered', 'approved', 'processed',
    'delivered', 'declined', 'canceled', 'exception'
  )),
  workflow_state text not null default 'pending' check (workflow_state in (
    'pending', 'accepted', 'needs_reconciliation', 'rejected'
  )),
  workflow_error text,
  owner_approval_required boolean not null default false,
  approval_threshold_cents integer check (approval_threshold_cents is null or approval_threshold_cents >= 0),
  order_value_cents integer not null check (order_value_cents >= 0),
  contains_preorder boolean not null default false,
  release_hold boolean not null default false,
  delivery_window text,
  receiving_contact text,
  receiving_instructions text,
  metadata jsonb not null default '{}'::jsonb,
  submitted_at timestamptz not null default now(),
  accepted_at timestamptz,
  updated_at timestamptz not null default now()
);

create unique index if not exists portal_order_order_number_idx
  on public.portal_order (order_number) where order_number is not null;
create unique index if not exists portal_order_monday_item_idx
  on public.portal_order (monday_item_id) where monday_item_id is not null;
create index if not exists portal_order_org_created_idx
  on public.portal_order (organization, submitted_at desc);
create index if not exists portal_order_store_created_idx
  on public.portal_order (location_license, submitted_at desc);
create index if not exists portal_order_workflow_idx
  on public.portal_order (workflow_state, updated_at desc);

create table if not exists public.portal_order_line (
  id bigint generated by default as identity primary key,
  order_id uuid not null references public.portal_order(id) on delete cascade,
  line_number integer not null check (line_number > 0),
  product_id text not null,
  product_name text not null,
  sku text,
  compliance_tag text,
  quantity integer not null check (quantity > 0 and quantity <= 9999),
  unit text not null default 'each' check (unit in ('each', 'gram')),
  unit_price_cents integer not null check (unit_price_cents >= 0),
  line_total_cents integer not null check (line_total_cents >= 0),
  order_mode text not null default 'standard' check (order_mode in ('standard', 'preorder')),
  release_state text not null default 'released' check (release_state in ('released', 'awaiting_release')),
  created_at timestamptz not null default now(),
  unique (order_id, line_number)
);

create index if not exists portal_order_line_product_idx
  on public.portal_order_line (product_id);

create table if not exists public.portal_order_event (
  id uuid primary key default gen_random_uuid(),
  order_id uuid not null references public.portal_order(id) on delete cascade,
  source text not null check (source in ('portal-intake', 'store-owner', 'store-user', 'internal', 'monday', 'system')),
  from_state text,
  to_state text not null,
  actor_id uuid references auth.users(id) on delete set null,
  actor_email text,
  raw_status text,
  note text,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create index if not exists portal_order_event_order_idx
  on public.portal_order_event (order_id, created_at asc);

create table if not exists public.portal_order_sync_outbox (
  id uuid primary key default gen_random_uuid(),
  order_id uuid not null references public.portal_order(id) on delete cascade,
  event_id uuid not null references public.portal_order_event(id) on delete cascade,
  target text not null default 'monday' check (target = 'monday'),
  state text not null default 'pending' check (state in ('pending', 'sent', 'failed')),
  attempts integer not null default 0 check (attempts >= 0),
  last_error text,
  last_attempt_at timestamptz,
  sent_at timestamptz,
  created_at timestamptz not null default now(),
  unique (event_id, target)
);

create index if not exists portal_order_sync_outbox_pending_idx
  on public.portal_order_sync_outbox (state, created_at asc);


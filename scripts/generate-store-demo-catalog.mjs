// Generates the Store demo catalog fixture from the checked-in, browser-verified
// Canix Marketplace snapshot. The snapshot JSON stays authoritative; the
// generated module exists only because edge functions cannot import files
// outside supabase/functions. Run with --check to fail on drift.
import { readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";

const root = resolve(import.meta.dirname, "..");
const sourceFile = "data/canix-marketplace-listings-2026-10-14.json";
const outputFile = "supabase/functions/_shared/store-demo-catalog.ts";
const check = process.argv.includes("--check");
// Display-only brand aliases confirmed by the business. The raw source brand is
// kept beside the display name; product identity is never merged or changed.
const BRAND_DISPLAY_ALIASES = { Cannaprints: "Cannaprint" };

const snapshot = JSON.parse(await readFile(resolve(root, sourceFile), "utf8"));
const { source, products } = snapshot;
if (source?.sourceMode !== "browser_verified_snapshot" || source?.snapshotScope !== "full_shop") {
  throw new Error("The demo catalog requires a browser-verified full-shop snapshot.");
}
if (!Array.isArray(products) || products.length !== source.declaredProductCount || products.length !== source.capturedProductCount) {
  throw new Error("Snapshot product count does not match the declared and captured counts.");
}

// Only fields the snapshot actually carries. SKU, pack/case size and release
// status are absent from the source and are never synthesized.
const text = ["marketplaceProductId", "productGid", "productName", "brandName", "itemCategoryName", "saleUnit", "productUrl"];
const whole = ["priceCents", "availableQuantity", "minimumOrderQuantity"];
const ids = new Set();
const rows = products.map((product, index) => {
  for (const field of text) {
    if (typeof product[field] !== "string" || !product[field].trim()) throw new Error(`Product ${index + 1} is missing ${field}.`);
  }
  for (const field of whole) {
    if (!Number.isInteger(product[field]) || product[field] < 0) throw new Error(`Product ${product.marketplaceProductId} has invalid ${field}.`);
  }
  if (product.minimumOrderQuantity < 1) throw new Error(`Product ${product.marketplaceProductId} has no usable minimum order quantity.`);
  if (product.hasImage !== Boolean(product.imageUrl)) throw new Error(`Product ${product.marketplaceProductId} has inconsistent image fields.`);
  if (ids.has(product.marketplaceProductId)) throw new Error(`Duplicate marketplace product ID ${product.marketplaceProductId}.`);
  ids.add(product.marketplaceProductId);
  return {
    marketplaceProductId: product.marketplaceProductId,
    productGid: product.productGid,
    productName: product.productName,
    brandName: BRAND_DISPLAY_ALIASES[product.brandName] ?? product.brandName,
    sourceBrandName: product.brandName,
    itemCategoryName: product.itemCategoryName,
    priceCents: product.priceCents,
    availableQuantity: product.availableQuantity,
    saleUnit: product.saleUnit,
    minimumOrderQuantity: product.minimumOrderQuantity,
    hasImage: product.hasImage,
    imageUrl: product.imageUrl || null,
    productUrl: product.productUrl,
  };
});

const provenance = {
  sourceFile,
  shopName: "Shop UrbanXtracts",
  shopSlug: source.shopSlug,
  sourceUrl: source.sourceUrl,
  sourceMode: source.sourceMode,
  snapshotScope: source.snapshotScope,
  capturedAt: source.capturedAt,
  syncRunId: source.syncRunId,
  productCount: rows.length,
};

const output = `// GENERATED by scripts/generate-store-demo-catalog.mjs from ${sourceFile}.
// Do not edit by hand; regenerate from the snapshot. Browser-verified listing
// snapshot only: not live inventory, and it carries no SKU, pack/case size or
// release status. brandName is the canonical display brand; sourceBrandName is
// the raw snapshot value.
export type DemoCatalogProduct = {
  marketplaceProductId: string;
  productGid: string;
  productName: string;
  brandName: string;
  sourceBrandName: string;
  itemCategoryName: string;
  priceCents: number;
  availableQuantity: number;
  saleUnit: string;
  minimumOrderQuantity: number;
  hasImage: boolean;
  imageUrl: string | null;
  productUrl: string;
};
export const DEMO_CATALOG_SOURCE = ${JSON.stringify(provenance, null, 2)} as const;
export const DEMO_CATALOG_PRODUCTS: readonly DemoCatalogProduct[] = [
${rows.map(row => "  " + JSON.stringify(row) + ",").join("\n")}
];
`;

const outputPath = resolve(root, outputFile);
if (check) {
  const current = await readFile(outputPath, "utf8").catch(() => "");
  if (current !== output) {
    console.error(`${outputFile} is out of date with ${sourceFile}. Run: node scripts/generate-store-demo-catalog.mjs`);
    process.exit(1);
  }
  console.log(`${outputFile} matches ${sourceFile} (${rows.length} products).`);
} else {
  await writeFile(outputPath, output);
  console.log(`Wrote ${outputFile} (${rows.length} products).`);
}
